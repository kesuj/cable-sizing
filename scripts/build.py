"""Build everything: data bundle + a single classic-script bundle so index.html works from file://
(double-click, USB stick, no internet, no server). No npm needed.

    python scripts/build.py
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

def step(name, *args):
    subprocess.run([sys.executable, str(ROOT / "scripts" / name), *args], check=True)

xlsx = ROOT / "source" / "conductor_calculator_original.xlsx"
try:
    import openpyxl  # noqa: F401  (only needed to re-read the Excel file)
    step("extract_excel.py", str(xlsx), str(ROOT / "data" / "lv_is.json"))
    step("extract_derating.py", str(xlsx), str(ROOT / "data" / "derating_is.json"))
except ImportError:
    print("openpyxl not installed: using the committed data/lv_is.json and data/derating_is.json")
step("build_lv_ref.py")
step("build_hv.py")
step("build_overhead.py")
import shutil
shutil.copy(ROOT / "research" / "iec_60364_5_52.json", ROOT / "data" / "iec_60364_5_52.json")
step("build_data.py")

IMPORT = re.compile(r'^import\s*\{([^}]*)\}\s*from\s*"([^"]+)";\s*$', re.M)
EXPORT_DECL = re.compile(r"^export\s+(?:async\s+)?(function|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_LIST = re.compile(r"^export\s*\{([^}]*)\};?\s*$", re.M)


def mod_id(path: Path) -> str:
    return path.relative_to(SRC).as_posix()


order: list[Path] = []


def visit(path: Path, seen=set()):
    if path in seen:
        return
    seen.add(path)
    for _, spec in IMPORT.findall(path.read_text(encoding="utf-8")):
        visit((path.parent / spec).resolve())
    order.append(path)


visit((SRC / "app.js").resolve())

out = ["// GENERATED by scripts/build.py — edit src/*.js instead.", "(() => {", "const __m = {};"]
for p in order:
    code = p.read_text(encoding="utf-8")
    names = []

    def imp(m, p=p):
        target = mod_id((p.parent / m.group(2)).resolve())
        binds = ", ".join(x.strip().replace(" as ", ": ") for x in m.group(1).split(",") if x.strip())
        return f'const {{ {binds} }} = __m["{target}"];'

    code = IMPORT.sub(imp, code)
    for kind, name in EXPORT_DECL.findall(code):
        names.append(name)
    code = EXPORT_DECL.sub(lambda m: m.group(0).replace("export ", "", 1), code)
    for m in EXPORT_LIST.findall(code):
        names += [x.strip() for x in m.split(",") if x.strip()]
    code = EXPORT_LIST.sub("", code)
    out.append(f'__m["{mod_id(p)}"] = (() => {{\n{code}\nreturn {{ {", ".join(names)} }};\n}})();')
out.append("})();")
dist = ROOT / "dist"
dist.mkdir(exist_ok=True)
(dist / "app.bundle.js").write_text("\n".join(out), encoding="utf-8")
print("dist/app.bundle.js:", " > ".join(mod_id(p) for p in order))
