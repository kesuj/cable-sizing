"""Bundle data/*.json into src/data.js so the web app works offline from file:// (no fetch)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
names = {"lv_is.json": "lvIs", "derating_is.json": "deratingIs", "lv_reactance.json": "lvReactance",
         "hv_is.json": "hvIs", "overhead.json": "overhead", "iec_60364_5_52.json": "iec"}
out = {}
for f, key in names.items():
    p = root / "data" / f
    if p.exists():
        out[key] = json.loads(p.read_text(encoding="utf-8"))
js = "// GENERATED by scripts/build_data.py from data/*.json — do not edit by hand.\nexport const DATA = " + json.dumps(out, separators=(",", ":")) + ";\n"
(root / "src" / "data.js").write_text(js, encoding="utf-8")
print("src/data.js:", ", ".join(out), f"({len(js)//1024} KB)")
